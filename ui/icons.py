_cache: dict[tuple, QIcon] = {}


def _render(name: str, color: str, size: int, stroke: float) -> QPixmap:
    body = _P.get(name, _P["sparkle"]).replace("currentColor", color)
    svg = (f'<svg xmlns="http://www.w3.org/2000/svg" viewBox="0 0 24 24" fill="none" stroke="{color}" stroke-width="{stroke}" '
           f'stroke-linecap="round" stroke-linejoin="round">{body}</svg>')
    r = QSvgRenderer(QByteArray(svg.encode()))
    scale = 2   # crisp on high-DPI screens
    img = QImage(size * scale, size * scale, QImage.Format.Format_ARGB32_Premultiplied)
    img.fill(Qt.GlobalColor.transparent)
    p = QPainter(img)
    r.render(p, QRectF(0, 0, size * scale, size * scale))
    p.end()
    pm = QPixmap.fromImage(img)
    pm.setDevicePixelRatio(scale)
    return pm


def icon(name: str, color: str = "#8a92a6", size: int = 18, stroke: float = 1.8) -> QIcon:
    key = (name, color, size, stroke)
    if key not in _cache:
        _cache[key] = QIcon(_render(name, color, size, stroke))
    return _cache[key]


def pixmap(name: str, color: str = "#8a92a6", size: int = 18, stroke: float = 1.8) -> QPixmap:
    return _render(name, color, size, stroke)
